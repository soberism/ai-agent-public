def display_value(domain, field, value, row=None):
    if domain == "meal" and field == "status":
        return {
            "draft": "待确认（已保存，尚未确认加入日历）",
            "planned": "已计划（已确认餐食安排）",
        }.get(str(value), STATUSES.get(str(value), str(value)))
    if domain == "voice_memo" and field == "status":
        if value == "draft":
            return "已保存，尚未转为待办或日程"
        if value == "converted":
            target = {"todo": "待办", "event": "日程"}.get(
                (row or {}).get("target_type")
            )
            return f"已转为{target}" if target else "已转换"
    return STATUSES.get(str(value), str(value))
